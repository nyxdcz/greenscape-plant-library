import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imageRoot = path.join(root, 'assets/images');
const outputRoot = path.join(imageRoot, 'thumbnails');
const manifestFile = path.join(outputRoot, 'manifest.json');
const moduleFile = path.join(root, 'assets/js/catalogue-thumbnails.mjs');
const settings = { width: 160, height: 160, fit: 'inside', withoutEnlargement: true, quality: 80 };
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export function localImageName(image) {
  if (!image || /^(?:[a-z][\w+.-]*:|\/)/i.test(image)) return null;
  const name = image.replace(/^assets\/images\//, '');
  return /^[\w-]+\.(?:webp|jpe?g|png)$/i.test(name) ? name : null;
}

export function thumbnailModule(entries) {
  const sources = Object.fromEntries(entries.map(entry => [entry.image, entry.thumbnail]));
  return `// Generated by scripts/catalogue-thumbnails.mjs.\nexport const THUMBNAILS = ${JSON.stringify(sources, null, 2)};\n`;
}

export function validateThumbnails({ images, manifest, read, moduleSource }) {
  const errors = [];
  if (JSON.stringify(manifest?.settings) !== JSON.stringify(settings) || !Array.isArray(manifest?.entries)) return ['Thumbnail settings or manifest are invalid.'];
  const entries = manifest.entries;
  if (!entries.every(entry => entry && typeof entry.image === 'string' && typeof entry.thumbnail === 'string'
    && /^[a-f0-9]{64}$/.test(entry.sourceHash) && /^[a-f0-9]{64}$/.test(entry.outputHash))) return ['Thumbnail manifest entries are invalid.'];
  if (JSON.stringify(entries.map(entry => entry.image)) !== JSON.stringify(images)) errors.push('Thumbnail manifest must match the published local photographs.');
  for (const entry of entries) {
    const expectedName = `${path.parse(entry.image).name}-${entry.sourceHash.slice(0, 12)}.webp`;
    if (localImageName(entry.image) !== entry.image || entry.thumbnail !== `thumbnails/${expectedName}`) {
      errors.push(`Invalid thumbnail path: ${entry.image}`);
      continue;
    }
    try {
      if (hash(read(entry.image)) !== entry.sourceHash) errors.push(`Photo changed; regenerate thumbnail: ${entry.image}`);
      const output = read(entry.thumbnail);
      if (hash(output) !== entry.outputHash || output.toString('ascii', 8, 12) !== 'WEBP') errors.push(`Thumbnail changed or invalid: ${entry.image}`);
      if (!(entry.width > 0 && entry.width <= settings.width && entry.height > 0 && entry.height <= settings.height)) errors.push(`Invalid thumbnail dimensions: ${entry.image}`);
    } catch {
      errors.push(`Missing photo or thumbnail: ${entry.image}`);
    }
  }
  if (moduleSource !== thumbnailModule(entries)) errors.push('Thumbnail application map is outdated.');
  return errors;
}

async function main() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, 'assets/js/data.js'), 'utf8'), sandbox);
  const images = [...new Set(sandbox.window.GREENSCAPE_PLANT_DATA.map(record => localImageName(record.image)).filter(Boolean))].sort();
  if (process.argv.includes('--check')) {
    const errors = validateThumbnails({ images, manifest: JSON.parse(fs.readFileSync(manifestFile, 'utf8')), read: file => fs.readFileSync(path.join(imageRoot, file)), moduleSource: fs.readFileSync(moduleFile, 'utf8') });
    if (errors.length) throw new Error(errors.join('\n'));
    console.log(`Thumbnail check passed: ${images.length} published photographs, source hashes, outputs, and application map.`);
    return;
  }
  const moduleFlag = process.argv.indexOf('--sharp-module');
  let sharp;
  try {
    sharp = (await import(moduleFlag === -1 ? 'sharp' : pathToFileURL(path.resolve(process.argv[moduleFlag + 1])).href)).default;
  } catch {
    throw new Error('Generation requires sharp. See docs/catalogue-performance.md for setup; --check needs only Node.');
  }
  fs.mkdirSync(outputRoot, { recursive: true });
  const entries = [];
  for (const image of images) {
    const source = fs.readFileSync(path.join(imageRoot, image));
    const sourceHash = hash(source);
    const thumbnail = `thumbnails/${path.parse(image).name}-${sourceHash.slice(0, 12)}.webp`;
    const { data, info } = await sharp(source).rotate().resize(settings.width, settings.height, { fit: settings.fit, withoutEnlargement: settings.withoutEnlargement }).webp({ quality: settings.quality }).toBuffer({ resolveWithObject: true });
    fs.writeFileSync(path.join(imageRoot, thumbnail), data);
    entries.push({ image, sourceHash, thumbnail, outputHash: hash(data), width: info.width, height: info.height });
  }
  fs.writeFileSync(manifestFile, JSON.stringify({ settings, entries }, null, 2) + '\n');
  fs.writeFileSync(moduleFile, thumbnailModule(entries));
  console.log(`Generated ${entries.length} thumbnails. Original photographs were not changed.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
